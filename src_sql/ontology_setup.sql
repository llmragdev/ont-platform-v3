CREATE OR REPLACE DATABASE ONTOLOGY_EDU;
USE DATABASE ONTOLOGY_EDU;
CREATE OR REPLACE SCHEMA RAW;
CREATE OR REPLACE SCHEMA ONTOLOGY;
CREATE OR REPLACE SCHEMA APP;

-- [02_create_raw_tables.sql]
USE SCHEMA RAW;
CREATE OR REPLACE TABLE CUSTOMERS (CUSTOMER_ID VARCHAR(10) PRIMARY KEY, NAME VARCHAR(100), SEGMENT VARCHAR(50), REGION VARCHAR(50), RISK_TIER VARCHAR(10));
CREATE OR REPLACE TABLE PRODUCTS (PRODUCT_ID VARCHAR(10) PRIMARY KEY, NAME VARCHAR(100), CATEGORY VARCHAR(50), UNIT_PRICE NUMBER(10, 2));
CREATE OR REPLACE TABLE ORDERS (ORDER_ID VARCHAR(10) PRIMARY KEY, CUSTOMER_ID VARCHAR(10), ORDER_DATE DATE, STATUS VARCHAR(20));
CREATE OR REPLACE TABLE ORDER_ITEMS (ITEM_ID VARCHAR(10) PRIMARY KEY, ORDER_ID VARCHAR(10), PRODUCT_ID VARCHAR(10), QUANTITY NUMBER(10));
