-- [03_create_ontology_views.sql]
USE SCHEMA ONTOLOGY;
CREATE OR REPLACE VIEW CUSTOMER_OBJECT AS SELECT CUSTOMER_ID, NAME, SEGMENT, REGION, RISK_TIER FROM RAW.CUSTOMERS;
CREATE OR REPLACE VIEW ORDER_OBJECT AS SELECT O.ORDER_ID, O.CUSTOMER_ID, O.ORDER_DATE, O.STATUS, SUM(I.QUANTITY * P.UNIT_PRICE) AS TOTAL_AMOUNT FROM RAW.ORDERS O JOIN RAW.ORDER_ITEMS I ON O.ORDER_ID = I.ORDER_ID JOIN RAW.PRODUCTS P ON I.PRODUCT_ID = P.PRODUCT_ID GROUP BY 1, 2, 3, 4;
CREATE OR REPLACE VIEW REL_CUSTOMER_PLACED_ORDER AS SELECT CUSTOMER_ID, ORDER_ID FROM RAW.ORDERS;

-- [04_create_workflow_actions.sql]
USE SCHEMA ONTOLOGY;
CREATE OR REPLACE TABLE ACTION_LOG (ACTION_ID INT AUTOINCREMENT, ACTION_NAME VARCHAR(50), TARGET_ID VARCHAR(50), ACTOR VARCHAR(50), COMMENT VARCHAR(200), OCCURRED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP());
USE SCHEMA APP;
CREATE OR REPLACE PROCEDURE APPROVE_ORDER(ORDER_ID VARCHAR, ACTOR VARCHAR, COMMENT VARCHAR) RETURNS STRING LANGUAGE SQL AS $$ BEGIN UPDATE RAW.ORDERS SET STATUS = 'Approved' WHERE ORDER_ID = :ORDER_ID; INSERT INTO ONTOLOGY.ACTION_LOG (ACTION_NAME, TARGET_ID, ACTOR, COMMENT) VALUES ('ApproveOrder', :ORDER_ID, :ACTOR, :COMMENT); RETURN 'Order ' || :ORDER_ID || ' has been approved.'; END; $$;
